#!/bin/bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
    CREATE USER "$INGESTOR_PG_USER" WITH PASSWORD '$INGESTOR_PG_PASSWORD';
    CREATE USER "$PROCESSOR_PG_USER" WITH PASSWORD '$PROCESSOR_PG_PASSWORD';

    CREATE SCHEMA IF NOT EXISTS "$MEASUREMENTS_SCHEMA";
    CREATE SCHEMA IF NOT EXISTS "$PROCESSED_SCHEMA";

    GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$INGESTOR_PG_USER";
    GRANT CONNECT ON DATABASE "$POSTGRES_DB" TO "$PROCESSOR_PG_USER";

    GRANT USAGE, CREATE ON SCHEMA "$MEASUREMENTS_SCHEMA" TO "$INGESTOR_PG_USER";
    GRANT USAGE, CREATE ON SCHEMA "$PROCESSED_SCHEMA" TO "$PROCESSOR_PG_USER";
    GRANT USAGE ON SCHEMA "$MEASUREMENTS_SCHEMA" TO "$PROCESSOR_PG_USER";

    ALTER DEFAULT PRIVILEGES IN SCHEMA "$MEASUREMENTS_SCHEMA" GRANT SELECT, INSERT, UPDATE ON TABLES TO "$INGESTOR_PG_USER";
    ALTER DEFAULT PRIVILEGES IN SCHEMA "$MEASUREMENTS_SCHEMA" GRANT SELECT TO "$PROCESSOR_PG_USER";
    ALTER DEFAULT PRIVILEGES IN SCHEMA "$PROCESSED_SCHEMA" GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO "$PROCESSOR_PG_USER";

    ALTER DEFAULT PRIVILEGES IN SCHEMA "$MEASUREMENTS_SCHEMA" GRANT USAGE, SELECT ON SEQUENCES TO "$INGESTOR_PG_USER";
    ALTER DEFAULT PRIVILEGES IN SCHEMA "$PROCESSED_SCHEMA" GRANT USAGE, SELECT ON SEQUENCES TO "$PROCESSOR_PG_USER";
EOSQL
